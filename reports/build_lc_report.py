para(doc, "**一句话总结：临沧2025年交出了\u201c+0.2%、二产-8.6%\u201d的停滞答卷，农业与边贸的亮点被工业与投资的塌方吞掉；但更该问的是——在茶咖果的禀赋与中缅通道的门户面前，这座城市能否把\u201c通道红利\u201d炼成\u201c工业+贸易+旅游\u201d的实证增长，让GDP重新跑起来。**当下看，牌好但未打出，短板在工业投资，成也通道、败也通道，唯有把通道做成产业，才能破题。")

